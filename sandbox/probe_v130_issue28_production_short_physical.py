"""#28 short TRUE physical PETSc TS after real production nonlinear_affine init.

Reuses the already native-tested short physical-time SCRIMP harness
sandbox/probe_v130_shallow_explicit_ts.py: exact original published
examples/shallow_water.py weak forms, original h0,p0 and zero boundary
controls; real BDF2 steps, frozen explicit gyro, saved full trajectory
and Hamiltonian. The ONLY mathematical change is selecting the new
explicit opt-in initializer instead of historical pseudo relaxation.

The production init_step entry point is wrapped to capture its actual
report and enforce strategy="nonlinear_affine". No special initial
physics, manufactured flow, ghost TS, or relaxation is introduced.
Hamiltonian drift is MEASURED, NOT required to be exactly zero:
BDF2 + explicit lagging is not an exact discrete gradient integrator.
"""

import argparse
import json
from pathlib import Path
from unittest.mock import patch

import numpy as np
from mpi4py import MPI
import scrimp as S

from probe_v130_shallow_explicit_ts import run_case

STRICT_F_A = 1e-11


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--dt", type=float, default=0.0001)
    ap.add_argument("--steps", type=int, default=4)
    args = ap.parse_args()
    if args.dt <= 0 or args.steps < 3:
        ap.error("dt must be positive; at least 3 real physical steps")
    mpi = MPI.COMM_WORLD
    init_reports = []
    original = S.DPHS.init_step

    def selected_init(self):
        # This is the ONLY override to the published time-setup
        # generated by the already-qualified short physical TS harness.
        # It avoids changing the original script's physical model.
        self.time_scheme["init_step_ts_type"] = "nonlinear_affine"
        result = original(self)
        report = getattr(self, "initialization_report", None)
        if not isinstance(report, dict):
            raise RuntimeError("Actual production initializer has no report")
        if report.get("strategy") != "nonlinear_affine" or report.get("status") != "PASS":
            raise RuntimeError("Physical TS used an unqualified initial strategy")
        if not report.get("differential_initial_exact"):
            raise RuntimeError("Production initializer modified original h0,p0")
        if report.get("native_final_algebraic_residual_l2", np.inf) > STRICT_F_A:
            raise RuntimeError("Production initialization accuracy gate missed")
        if not report.get("accuracy_target_met"):
            raise RuntimeError("Production initializer did not meet accuracy target")
        init_reports.append(dict(report))
        return result

    # Exact original published mesh=.1. The prior passing short
    # physical TS harness patches time horizon/solver only, not PDE,
    # initial states, FE families or physical boundary controls.
    with patch.object(S.DPHS, "init_step", selected_init):
        physical = run_case(
            mesh=0.1, dt=args.dt, steps=args.steps,
            manufactured=False, mpi=mpi,
        )
    if len(init_reports) != 1:
        raise RuntimeError(
            f"Expected exactly one REAL opt-in initialization; got {len(init_reports)}"
        )
    if physical["manufactured_nonzero_G_initial_data"]:
        raise RuntimeError("Published initial momentum was changed")
    if physical["p_initial_expression"] != "[0.,0.]":
        raise RuntimeError("Original published p0 expression changed")
    if physical["time_steps"] != args.steps or physical["TS_accepted_steps"] != args.steps:
        raise RuntimeError("Real physical BDF2 accepted step count mismatch")
    if physical["TS_rejected_steps"] or physical["TS_SNES_failures"]:
        raise RuntimeError("Real physical TS suffered rejections or SNES failures")
    if physical["main_IFunction_checks"] < args.steps:
        raise RuntimeError("No real TS nonlinear residual observations")
    if physical["max_frozen_explicit_RHS_drift"] != 0.:
        raise RuntimeError("Explicit gyro changed within main Newton iterations")
    times = np.asarray(physical["times"])
    z = np.asarray(physical["full_state_trajectory"])
    hamiltonian = np.asarray(physical["hamiltonian"])
    if (len(times) < 2 or len(z) != len(times)
            or not np.isfinite(hamiltonian).all()
            or not np.isfinite(z).all()):
        raise RuntimeError("Incomplete/nonfinite production physical trajectory")
    if not np.array_equal(times, np.asarray(physical["times"])):
        raise RuntimeError("Unexpected physical trajectory loss")
    report = {
        "schema": "scrimp-v130-issue28-production-affine-short-physical-ts-v1",
        "status": "PASS_NATIVE_PHYSICAL_TS_SMOKE",
        "source": "original published examples/shallow_water.py",
        "original_mesh": 0.1,
        "physical_initial_h0_p0_unchanged": True,
        "original_homogeneous_boundary_controls_unchanged": True,
        "mpi_ranks": int(mpi.Get_size()),
        "initialization_strategy": "nonlinear_affine",
        "production_initialization_report": init_reports[0],
        "physical": physical,
        "hamiltonian_drift_measured": True,
        "exact_Hamiltonian_balance_qualified": False,
        "mesh_independent_constraint_acceptance_qualified": False,
        "rotating_high_index_initialization_qualified": False,
    }
    if mpi.Get_rank() == 0:
        args.out.mkdir(parents=True, exist_ok=True)
        filename = f"production_affine_physical_{mpi.Get_size()}r.json"
        (args.out / filename).write_text(
            json.dumps(report, indent=2) + "\n", encoding="utf-8"
        )
        print(
            f"ISSUE28 PRODUCTION AFFINE REAL TS MPI={mpi.Get_size()} "
            f"PASS accepted={physical['TS_accepted_steps']} "
            f"initial_Fa={init_reports[0]['native_final_algebraic_residual_l2']:.9g} "
            f"delta_H={physical['signed_H_final_minus_H_initial']:.9g} "
            f"relative_H_drift={physical['relative_abs_H_change']:.9g} "
            f"frozen_G_drift={physical['max_frozen_explicit_RHS_drift']:.9g}",
            flush=True,
        )


if __name__ == "__main__":
    main()
